package blobstore

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"hash"
	"strings"
)

// hexSHA256Len is the length of a lowercase hex SHA-256 digest. Every hash this
// service accepts from the wire is checked against it before it becomes a path
// segment, which is most of what makes the layout safe: a 64-character
// [0-9a-f] string cannot be "..", cannot contain a separator, and cannot escape
// the data directory.
const hexSHA256Len = 64

// validateBlobKey is the gate between the wire and the filesystem. Everything
// that turns a caller-supplied group, namespace or hash into a path goes through
// it — Store.Path's own doc comment says so — so a traversal attempt is refused
// at one place rather than defended against at each call site.
func validateBlobKey(group, namespace, hash string) error {
	if err := validateGroupName(group); err != nil {
		return err
	}
	if err := validateNamespace(namespace); err != nil {
		return err
	}
	return validateContentHash(hash)
}

// validateGroupName accepts the shape a volume group name may have: a single
// path segment of letters, digits, `-` and `_`. The group name is the first path
// segment of every file the group holds.
func validateGroupName(group string) error {
	if group == "" {
		return fmt.Errorf("group is empty")
	}
	if len(group) > 64 {
		return fmt.Errorf("group %q is longer than 64 characters", group)
	}
	for _, r := range group {
		if !isNameRune(r) {
			return fmt.Errorf("group %q contains %q, which is not a letter, digit, '-' or '_'", group, r)
		}
	}
	return nil
}

// validateNamespace accepts the fleet's namespace form: an absolute path of
// segments, each letters, digits, `-` or `_` ("/" for root, "/tenants/acme" for
// a tenant). It refuses "." and ".." as segments explicitly rather than relying
// on the character set, because both are made only of accepted characters and
// both are exactly what a traversal needs.
func validateNamespace(namespace string) error {
	if namespace == "" {
		return fmt.Errorf("namespace is empty")
	}
	if !strings.HasPrefix(namespace, "/") {
		return fmt.Errorf("namespace %q is not absolute", namespace)
	}
	if len(namespace) > 256 {
		return fmt.Errorf("namespace %q is longer than 256 characters", namespace)
	}
	if namespace == "/" {
		return nil
	}
	for _, seg := range strings.Split(strings.TrimPrefix(namespace, "/"), "/") {
		if seg == "" {
			return fmt.Errorf("namespace %q has an empty segment", namespace)
		}
		if seg == "." || seg == ".." {
			return fmt.Errorf("namespace %q has a relative segment", namespace)
		}
		for _, r := range seg {
			if !isNameRune(r) {
				return fmt.Errorf("namespace %q contains %q, which is not a letter, digit, '-' or '_'", namespace, r)
			}
		}
	}
	return nil
}

// validateContentHash accepts exactly a lowercase hex SHA-256.
func validateContentHash(h string) error {
	if len(h) != hexSHA256Len {
		return fmt.Errorf("content hash %q is not %d hex characters", h, hexSHA256Len)
	}
	for _, r := range h {
		if (r < '0' || r > '9') && (r < 'a' || r > 'f') {
			return fmt.Errorf("content hash %q is not lowercase hex", h)
		}
	}
	return nil
}

func isNameRune(r rune) bool {
	return (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') || r == '-' || r == '_'
}

// namespaceDir encodes a namespace path as one filesystem segment. See
// BlobKey.String for why `:` is the substitute and why it is total.
func namespaceDir(namespace string) string {
	return strings.ReplaceAll(namespace, "/", ":")
}

// namespaceFromDir is namespaceDir's inverse.
func namespaceFromDir(dir string) string {
	return strings.ReplaceAll(dir, ":", "/")
}

// sanitizeTempPrefix reduces an upload id to something safe to use as a temp
// file name prefix. The id is generated by this service and is already safe;
// this exists so that a future id shape cannot turn a temp name into a path.
func sanitizeTempPrefix(s string) string {
	var b strings.Builder
	for _, r := range s {
		if isNameRune(r) {
			b.WriteRune(r)
		}
	}
	if b.Len() == 0 {
		return "upload"
	}
	return b.String()
}

// hasher wraps SHA-256 so the hex form is produced in one place. The hash is
// computed ON THE STREAM as the bytes pass (R5) — native and exact, which is
// what the v2 cloud design could not have.
type hasher struct{ h hash.Hash }

func newHasher() *hasher { return &hasher{h: sha256.New()} }

func (h *hasher) Write(p []byte) (int, error) { return h.h.Write(p) }

func (h *hasher) hex() string { return hex.EncodeToString(h.h.Sum(nil)) }

// sha256Hex is the one-shot form, used to key a BlobLink by sha256(token).
func sha256Hex(b []byte) string {
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:])
}
